import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import sharp from "sharp";
const root = resolve(import.meta.dirname, "..");
const heroes = resolve(root, "packages/web/src/assets/vfx/heroes");
const bounds = {}, auraBounds = {}, peaks = {};
for (const hero of readdirSync(heroes).sort()) {
  let manifest;
  try { manifest = JSON.parse(readFileSync(resolve(heroes, hero, "expansion/manifest.json"), "utf8")); } catch { continue; }
  for (const art of manifest.assets) {
    const role = art.filename.split("/").at(-1);
    if (role !== "select_ring.png" && role !== "deploy.png" && role !== "commander_aura.png") continue;
    const { data, info } = await sharp(resolve(root, "packages/web/src/assets", art.filename)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    if (role === "select_ring.png" || role === "commander_aura.png") {
      let left = info.width, top = info.height, right = 0, bottom = 0;
      for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
        if (data[(y * info.width + x) * 4 + 3] < 24) continue;
        left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y);
      }
      (role === "select_ring.png" ? bounds : auraBounds)[hero] = { left, top, width: right - left + 1, height: bottom - top + 1 };
    } else {
      const energy = Array.from({ length: art.frames }, (_, frame) => {
        let light = 0;
        for (let y = 0; y < art.frameHeight; y++) for (let x = 0; x < art.frameWidth; x++) {
          const i = (y * info.width + frame * art.frameWidth + x) * 4;
          light += data[i + 3] / 255 * (data[i] * .2126 + data[i + 1] * .7152 + data[i + 2] * .0722);
        }
        return light;
      });
      const peak = Math.max(...energy);
      const plateau = energy.map((value, frame) => ({ value, frame })).filter(({ value }) => value >= peak * .98);
      const frame = plateau[Math.floor((plateau.length - 1) / 2)].frame;
      peaks[hero] = Number(((frame + .5) / art.frames).toFixed(5));
    }
  }
}
const target = resolve(root, "packages/web/src/features/vfx/expansionPresence.generated.ts");
writeFileSync(target, "// Generated by scripts/generate-vfx-presence-metadata.mjs; source PNG bytes remain untouched.\n" +
  "// Selection bounds use alpha >= 24. Reveal reaches 1 at the center of the authored brightest frame.\n" +
  `export const selectionRingBounds: Readonly<Record<string, { left: number; top: number; width: number; height: number }>> = ${JSON.stringify(bounds, null, 2)};\n` +
  `export const commanderAuraBounds: Readonly<Record<string, { left: number; top: number; width: number; height: number }>> = ${JSON.stringify(auraBounds, null, 2)};\n` +
  `export const deploymentRevealFractions: Readonly<Record<string, number>> = ${JSON.stringify(peaks, null, 2)};\n`);
console.log(JSON.stringify({ selectionRings: Object.keys(bounds).length, deployPeaks: Object.keys(peaks).length, revealFractions: peaks }));
