import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const state = JSON.parse(readFileSync(resolve(root, "docs/assets/vfx-workflow/integration-state.json"), "utf8"));
const lines = ["// Generated by scripts/generate-vfx-expansion-catalog.mjs. Bindings live in expansionPresentation.ts.",
  "export const expansionAssets = {"];
for (const row of state.assets) {
  const manifest = JSON.parse(readFileSync(resolve(root, "packages/web/src/assets/vfx/heroes", row.heroId, "expansion/manifest.json"), "utf8"));
  const asset = manifest.assets.find(asset => asset.id === row.id);
  const role = row.filename.split("/").at(-1).replace(/\.png$/, "");
  lines.push(`  ${JSON.stringify(`expansion.${row.heroId}.${role}`)}: { heroId: ${JSON.stringify(row.heroId)}, role: ${JSON.stringify(role)}, asset: new URL(${JSON.stringify(`../../assets/${row.filename}`)}, import.meta.url).href, frames: ${asset.frames}, frameWidth: ${asset.frameWidth}, frameHeight: ${asset.frameHeight}, durationMs: ${asset.durationMs ?? 0}, geometry: ${JSON.stringify(asset.geometry)}, layer: ${JSON.stringify(asset.layer)}, authoredFacing: ${JSON.stringify(asset.authoredFacing)}, anchorPoint: { x: ${asset.anchorPoint[0]}, y: ${asset.anchorPoint[1]} } },`);
}
lines.push("} as const;", "export type ExpansionEffectId = keyof typeof expansionAssets;", "");
writeFileSync(resolve(root, "packages/web/src/features/vfx/expansionCatalog.generated.ts"), lines.join("\n"));
console.log(`Generated ${state.assets.length} definitions; registration does not imply a gameplay binding.`);
