import { readFileSync, writeFileSync } from "node:fs";
const manifest = new URL("../src/assets/heroVfxCoverage.json", import.meta.url);
const rows = JSON.parse(readFileSync(manifest, "utf8"));
const statuses = rows.reduce(
  (result, row) => ({ ...result, [row.status]: (result[row.status] ?? 0) + 1 }),
  {},
);
const table = rows
  .map(
    (row) =>
      `| ${row.hero} | [${row.file}](vfx/heroes/${row.hero}/${row.file}) | ${row.ability} | ${row.key ?? "—"} | ${row.placement} | ${row.trigger} | ${row.status === "PERSISTENT_CONNECTED" ? "persistent" : row.status.startsWith("BLOCKED") ? "blocked" : "one-shot"} | ${row.composite ?? "—"} | ${row.frames} × ${row.frameWidth} × ${row.frameHeight}; ${row.durationMs ? `${row.durationMs} ms; ${((row.frames * 1000) / row.durationMs).toFixed(2)} fps` : "static"} | ${row.status} |`,
  )
  .join("\n");
writeFileSync(
  new URL("../src/assets/HERO_VFX_COVERAGE.md", import.meta.url),
  `# Targeted hero VFX coverage: 45 PNG files

Generated by <code>node packages/web/scripts/generate-hero-vfx-coverage.mjs</code> from [heroVfxCoverage.json](heroVfxCoverage.json). Counts are physical PNGs, not semantic cues.

Initial audit: 137 hero PNGs; 45 absent from the runtime registry, in ${new Set(rows.map((row) => row.hero)).size} hero folders. All 45 inspected as PNGs; all frames are 128 × 128. Registry additions group primary/accent into synchronized layers.

Final counts: ${Object.entries(statuses)
    .map(([status, count]) => `${status}: **${count}**`)
    .join("; ")}. Intentionally unused: **0**. REGISTERED_ONLY: **0**. Total: **45**.

| Hero | Physical PNG | Ability/status | Runtime key | Placement | Authoritative trigger/state | Lifetime | Composite | Frames × frame dimensions; authored timing | Status |
|---|---|---|---|---|---|---|---|---|---|
${table}

Persistent strips use a static representative frame, without permanent animation loops. Their authored duration describes the source strip, not status lifetime. The Gaster charge strip is fitted to the existing 400 ms charge phase; its authored duration is 650 ms. Final Chord uses authorized resolved attack segments and a source pulse if no authorized legs exist; no blocker locations are reconstructed.

The only blocked file is <code>undyne/shift.png</code>. Direction Shift (<code>undyneSwitchDirection</code>) has canonical ability metadata but no activation/forced-movement resolver. Prerequisite: implement and test the actual mechanic in a separate gameplay task, then connect a recipient-safe confirmed movement event. No speculative trigger or unused registry entry was added.

Implementation, replacements, validation and browser evidence: [final report](../../../../docs/assets/HERO_VFX_FINAL_45.md).
`,
  "utf8",
);
console.log(`Generated coverage for ${rows.length} physical assets.`);
