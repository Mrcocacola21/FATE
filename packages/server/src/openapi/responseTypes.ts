export type Rooms = ReturnType<typeof listRoomSummaries>;
export type Room = Rooms[number];
export type CreatedRoom = ReturnType<typeof toCreatedRoomDto>;
export type CreatedGame = ReturnType<typeof toCreatedGameDto>;
export type CompetitiveConfig = ReturnType<typeof readLeaderboardConfig>;
export type Capabilities = { testRooms: ReturnType<typeof getTestRoomCapabilities> };
export type Hero = HeroMeta;
export type Heroes = HeroMeta[];
export type ServerInfo = ReturnType<typeof serverInfo>;
export type Health = ReturnType<typeof healthStatus>;

