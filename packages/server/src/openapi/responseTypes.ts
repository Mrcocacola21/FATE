  AuditEvents: AuditEvents;
  MatchmakingStatus: MatchmakingStatus;
  Rooms: Rooms;
  Room: Room;
  CreatedRoom: CreatedRoom;
  CreatedGame: CreatedGame;
  CompetitiveConfig: CompetitiveConfig;
