export type PublicProfile = { profile: ReturnType<typeof toPublicProfileDto> };
export type MatchDetails = Awaited<ReturnType<MatchService["getFinishedMatchDetails"]>>;
export type MatchHistory = Awaited<ReturnType<MatchHistoryService["getUserMatchHistory"]>>;
